// Regenerate src/client/keywords.js from the Lexon compiler's own grammar.
// The keyword set is derived, never hand-maintained, so the highlighter
// cannot drift from the grammar: `lexon -K grammar/english.lgf`.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { homedir } from 'node:os'

const BIN = process.env.LEXON_BIN || `${homedir()}/Code/lexon/bin/lexon`
const GRAMMAR = process.env.LEXON_GRAMMAR || `${homedir()}/Code/lexon/grammar/english.lgf`

const out = execFileSync(BIN, ['-K', GRAMMAR], { encoding: 'utf8' })
const words = [...new Set(out.split(/\s+/).filter(Boolean))]

writeFileSync(
  new URL('../src/client/keywords.js', import.meta.url),
  `// GENERATED by tools/gen-keywords.mjs — do not edit by hand.\n` +
    `// ${words.length} keywords from \`lexon -K\` over grammar/english.lgf\n` +
    `export default ${JSON.stringify(words)}\n`,
)
console.log(`wrote ${words.length} keywords to src/client/keywords.js`)
